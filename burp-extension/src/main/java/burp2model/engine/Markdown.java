package burp2model.engine;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;

/** A readable summary of the model for notes and reports: stack, leads, endpoints, open questions. Every row cites evidence. */
public final class Markdown {
    private Markdown() {}

    private static String cell(Object o) {
        return String.valueOf(o).replace("|", "\\|").replace("\n", " ");
    }

    private static String ev(List<Integer> ids) {
        List<String> p = new ArrayList<>();
        for (int i = 0; i < Math.min(3, ids.size()); i++) {
            p.add("ev_" + ids.get(i));
        }
        return String.join(", ", p);
    }

    @SuppressWarnings("unchecked")
    public static String summary(Model m) {
        StringBuilder sb = new StringBuilder();
        Map<String, Object> c = m.counts();
        sb.append("# ").append(m.name).append("\n\n");
        sb.append(c.get("endpoints")).append(" API endpoints on ").append(c.get("routes")).append(" pages, from ").append(m.evidenceLog.size())
                .append(" captured requests. Scope: ").append(String.join(", ", m.scope)).append(".\n\n");
        Map<String, Object> st = (Map<String, Object>) c.get("api_state");
        sb.append("Code vs runtime: ").append(st.getOrDefault("BOTH", 0L)).append(" in both, ").append(st.getOrDefault("RUNTIME_ONLY", 0L))
                .append(" traffic only, ").append(st.getOrDefault("STATIC_ONLY", 0L)).append(" named in code and never called.\n\n");
        if (!m.stack.isEmpty()) {
            sb.append("## Technology stack\n\n");
            for (Map<String, Object> t : m.stack) {
                String v = String.valueOf(t.get("version"));
                sb.append("- ").append(t.get("name")).append(v.isEmpty() ? "" : " " + v).append(" (").append(t.get("category")).append(")\n");
            }
            sb.append('\n');
        }
        List<Analysis.Lead> leads = Analysis.leads(m);
        sb.append("## To check (").append(leads.size()).append(")\n\nLeads are hypotheses to verify in an authorised session, never findings.\n\n");
        sb.append("| Endpoint | Why | Do next | Evidence |\n| --- | --- | --- | --- |\n");
        for (Analysis.Lead l : leads.subList(0, Math.min(40, leads.size()))) {
            Analysis.Signal s = l.signals().get(0);
            sb.append("| `").append(cell(l.endpoint().label)).append("` | ").append(cell(s.title())).append(" | ").append(cell(s.next())).append(" | ")
                    .append(ev(l.endpoint().evidence)).append(" |\n");
        }
        sb.append("\n## Endpoints\n\n| Endpoint | State | Statuses | Roles | Evidence |\n| --- | --- | --- | --- | --- |\n");
        List<Model.Node> eps = new ArrayList<>();
        m.nodes.values().stream().filter(n -> n.type.equals("endpoint")).forEach(eps::add);
        eps.sort(Comparator.comparing(n -> n.label));
        for (Model.Node n : eps) {
            sb.append("| `").append(cell(n.label)).append("` | ").append(n.attrs.get("api_state")).append(" | ")
                    .append(cell(String.valueOf(n.attrs.getOrDefault("statuses", "")).replace("[", "").replace("]", ""))).append(" | ")
                    .append(String.join(", ", n.roles)).append(" | ").append(ev(n.evidence)).append(" |\n");
        }
        sb.append("\n## Open questions\n\n| About | Not known | Smallest next step |\n| --- | --- | --- |\n");
        for (Map<String, Object> g : Analysis.gaps(m)) {
            sb.append("| `").append(cell(g.get("entity"))).append("` | ").append(cell(g.get("unknown"))).append(" | ").append(cell(g.get("next"))).append(" |\n");
        }
        sb.append("\n## Third parties\n\n");
        m.nodes.values().stream().filter(n -> n.type.equals("third_party")).sorted(Comparator.comparing(n -> n.label))
                .forEach(n -> sb.append("- ").append(n.label).append(" (").append(ev(n.evidence)).append(")\n"));
        sb.append("\nGenerated by burp2model. Values are masked; every row cites the request that shows it.\n");
        return sb.toString();
    }
}
